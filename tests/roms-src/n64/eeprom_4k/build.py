#!/usr/bin/env python3
"""Original 4 Kbit Joybus EEPROM register-output cartridge; no SDK bytes."""
import argparse
import importlib.util
from pathlib import Path

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location('n64_assembler', HERE.parent / 'dp_registers/build.py')
asm = importlib.util.module_from_spec(spec)
spec.loader.exec_module(asm)
SUITE = 'eeprom_4k'
BLOCKS = 64
PATTERNS = 256
CASES = BLOCKS * (PATTERNS + 2)


def payload(block, pattern):
    return bytes(((block * 37 + pattern * 59 + lane * 101) ^
                  ((pattern << (lane & 3)) & 255)) & 255 for lane in range(8))


def build(wrong_capture=False):
    p = asm.Program()
    p.data[:4] = bytes.fromhex('80371240')
    p.data[8:12] = bytes.fromhex('80000400')
    p.data[0x20:0x34] = b'VELOCE EEPROM 4K    '
    p.data[0x34:0x3c] = b'V64HB001'
    p.data[0x3c:0x40] = b'E4K1'
    p.i(15, 0, 30, 0xbff0)       # debug output
    p.i(15, 0, 24, 0xa480)       # SI registers
    p.i(15, 0, 10, 0xa003)       # uncached scratch, clear of copied ROM table
    p.address(20, 'table')
    p.puts('header')

    def packet(name):
        p.address(9, name)
        for offset in range(0, 64, 8):
            p.i(55, 9, 11, offset)
            p.i(63, 10, 11, offset)
        p.i(40, 10, 18, 7)     # cartridge block address
        p.i(43, 24, 10, 0)     # SI DRAM address
        p.i(43, 24, 0, 16)     # RDRAM -> PIF: format packet
        p.i(43, 24, 0, 24)     # acknowledge completion
        p.i(43, 24, 0, 4)      # PIF -> RDRAM: execute and observe

    def read_row(mutant=False):
        packet('read_packet')
        p.i(55, 10, 5, 8)     # eight EEPROM bytes returned by SI
        if mutant:
            p.i(14, 5, 5, 1)
        p.puts('row')
        p.jump(3, 'hex')
        p.r(0x25, 14, 0, 5)   # OR a1,t6,zero: last write status (or zero)
        p.jump(3, 'hex')
        p.i(9, 0, 8, 10)
        p.i(40, 30, 8, 0)

    # Every block is blank before the guest's first write.
    p.i(9, 0, 18, 0)
    p.i(9, 0, 21, BLOCKS)
    p.mark('blank')
    p.i(9, 0, 14, 0)
    read_row()
    p.i(9, 18, 18, 1)
    p.branch(5, 18, 21, 'blank')

    p.i(9, 0, 18, 0)
    p.i(9, 0, 22, PATTERNS)
    p.mark('block')
    p.i(9, 0, 19, 0)
    p.mark('pattern')
    p.i(55, 20, 13, 0)
    p.i(9, 20, 20, 8)
    packet('write_packet')
    # The payload is placed after the command and block byte. Reformat once
    # more so the captured SI read packet contains the guest-generated bytes.
    p.i(63, 10, 13, 8)
    p.i(43, 24, 10, 0)
    p.i(43, 24, 0, 16)
    p.i(43, 24, 0, 24)
    p.i(43, 24, 0, 4)
    p.i(36, 10, 14, 16)       # write response status
    read_row(wrong_capture)
    p.i(9, 19, 19, 1)
    p.branch(5, 19, 22, 'pattern')
    p.i(9, 18, 18, 1)
    p.branch(5, 18, 21, 'block')

    # Re-read all addresses after every block has been overwritten 256 times;
    # this rejects block aliasing even when each immediate write/read agrees.
    p.i(9, 0, 18, 0)
    p.mark('final')
    p.i(9, 0, 14, 0)
    read_row()
    p.i(9, 18, 18, 1)
    p.branch(5, 18, 21, 'final')
    p.puts('complete')
    p.i(43, 30, 0, 4)
    p.mark('halt')
    p.branch(4, 0, 0, 'halt')
    asm.output_routines(p)
    p.string('header', f'VELOCE 1 n64 {SUITE}\nBEGIN eeprom cases={CASES} words=2\n')
    p.string('row', 'REG r=')
    p.string('complete', f'LOG complete cases={CASES}\nEND observations_complete\n')
    while p.pc & 7:
        p.data.append(0)
    p.mark('write_packet')
    packet_bytes = bytearray(64)
    packet_bytes[:18] = bytes([0, 0, 0, 0, 10, 1, 5, 0] + [0] * 8 + [0, 254])
    packet_bytes[63] = 1
    p.data.extend(packet_bytes)
    p.mark('read_packet')
    packet_bytes = bytearray(64)
    packet_bytes[:17] = bytes([0, 0, 0, 0, 2, 8, 4, 0] + [0] * 8 + [254])
    packet_bytes[63] = 1
    p.data.extend(packet_bytes)
    p.mark('table')
    for block in range(BLOCKS):
        for pattern in range(PATTERNS):
            p.data.extend(payload(block, pattern))
    p.resolve()
    return bytes(p.data)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('output', nargs='?', type=Path, default=HERE / f'{SUITE}.z64')
    args = parser.parse_args()
    args.output.write_bytes(build())
